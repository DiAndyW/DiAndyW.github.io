// One-off: bake a finer Natural Earth coastline around LA for the globe intro's deep zoom.
// Usage: node scripts/generate-socal-detail.mjs <ne_50m_land.geojson> <out.ts>
// Source: https://cdn.jsdelivr.net/gh/nvkelso/natural-earth-vector@v5.1.2/geojson/ne_50m_land.geojson
import { readFileSync, writeFileSync } from 'node:fs';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
    console.error('usage: node scripts/generate-socal-detail.mjs <in.geojson> <out.ts>');
    process.exit(1);
}

// Keep every land ring that touches this window; it's wider than the patch so shapes aren't cut at its edge.
const WINDOW = { lonMin: -140, lonMax: -90, latMin: 12, latMax: 55 };
// Minimum spacing between kept points, in degrees: fine near LA where the zoom ends, coarser elsewhere.
const NEAR_LA = { lonMin: -125, lonMax: -112, latMin: 30, latMax: 38 };
const STEP_NEAR = 0.05;
const STEP_FAR = 0.2;
const isNearLA = (lon, lat) => lon > NEAR_LA.lonMin && lon < NEAR_LA.lonMax && lat > NEAR_LA.latMin && lat < NEAR_LA.latMax;

const geo = JSON.parse(readFileSync(input, 'utf8'));
const rings = [];
for (const feature of geo.features) {
    const { type, coordinates } = feature.geometry;
    const polygons = type === 'Polygon' ? [coordinates] : type === 'MultiPolygon' ? coordinates : [];
    for (const polygon of polygons) rings.push(polygon[0]); // outer ring only
}

const touches = (ring) => {
    const lons = ring.map(([lon]) => lon);
    const lats = ring.map(([, lat]) => lat);
    return (
        Math.max(...lons) >= WINDOW.lonMin &&
        Math.min(...lons) <= WINDOW.lonMax &&
        Math.max(...lats) >= WINDOW.latMin &&
        Math.min(...lats) <= WINDOW.latMax
    );
};

// Degree units: x = lon + 180, y = 90 - lat (the 200x100 continents map scaled by 1.8).
const parts = [];
for (const ring of rings.filter(touches)) {
    const kept = [];
    for (const [lon, lat] of ring) {
        const point = [+(lon + 180).toFixed(2), +(90 - lat).toFixed(2)];
        const last = kept[kept.length - 1];
        const step = isNearLA(lon, lat) ? STEP_NEAR : STEP_FAR;
        if (!last || Math.hypot(point[0] - last[0], point[1] - last[1]) >= step) kept.push(point);
    }
    if (kept.length < 3) continue;
    parts.push('M' + kept.map(([x, y]) => `${x} ${y}`).join('L') + 'Z');
}

writeFileSync(
    output,
    `// Generated by scripts/generate-socal-detail.mjs from Natural Earth 50m land. Do not edit by hand.\n` +
        `// Degree units: x = lon + 180, y = 90 - lat.\n` +
        `export const SOCAL_DETAIL_PATH = "${parts.join('')}";\n`,
);
console.log(`${parts.length} shapes written to ${output}`);
