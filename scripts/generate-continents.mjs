// One-off: bake Natural Earth land polygons into a static SVG path for the globe intro.
// Usage: node scripts/generate-continents.mjs <ne_110m_land.geojson> <out.ts>
// Source: https://cdn.jsdelivr.net/gh/nvkelso/natural-earth-vector@v5.1.2/geojson/ne_110m_land.geojson
import { readFileSync, writeFileSync } from 'node:fs';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
    console.error('usage: node scripts/generate-continents.mjs <in.geojson> <out.ts>');
    process.exit(1);
}

const MAP_W = 200;
const MAP_H = 100;
const MIN_STEP = 1.0;

// Same projection as lonLatToMap in src/components/intro/globeMath.ts.
const project = ([lon, lat]) => [((lon + 180) / 360) * MAP_W, ((90 - lat) / 180) * MAP_H];

const geo = JSON.parse(readFileSync(input, 'utf8'));
const rings = [];
for (const feature of geo.features) {
    const { type, coordinates } = feature.geometry;
    const polygons = type === 'Polygon' ? [coordinates] : type === 'MultiPolygon' ? coordinates : [];
    for (const polygon of polygons) rings.push(polygon[0]); // outer ring only
}

const parts = [];
for (const ring of rings) {
    if (Math.max(...ring.map(([, lat]) => lat)) < -60) continue; // Antarctica

    const kept = [];
    for (const point of ring.map(project)) {
        const last = kept[kept.length - 1];
        if (!last || Math.hypot(point[0] - last[0], point[1] - last[1]) >= MIN_STEP) kept.push(point);
    }
    if (kept.length < 4) continue;

    const fmt = ([x, y]) => `${Math.round(x * 10) / 10} ${Math.round(y * 10) / 10}`;
    parts.push(`M${fmt(kept[0])}` + kept.slice(1).map((p) => `L${fmt(p)}`).join('') + 'Z');
}

writeFileSync(
    output,
    `// Generated by scripts/generate-continents.mjs from Natural Earth 110m land. Do not edit by hand.\n` +
        `export const CONTINENTS_PATH = "${parts.join('')}";\n`,
);
console.log(`${parts.length} shapes written to ${output}`);
